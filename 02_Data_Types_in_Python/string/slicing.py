# # Slicing is used to extract the specific part of the string without
# change the original string.
# # string[start : end : step]
# start → Kahan se start karna hai.
# end → Kahan tak lena hai (end index include nahi hota).
# step → Kitne characters skip karne hain.
name="Pythonisthebestprogrammminglanguage"
print(name[0:10:2])