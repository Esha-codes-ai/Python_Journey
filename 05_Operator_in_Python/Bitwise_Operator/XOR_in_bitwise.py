# bitwise (^) is a very important operator in python which is used to perform XOR operation on two integers. It returns 1 if the bits are different and 0 if they are the same.
a = 5  # binary: 101    
b = 3  # binary: 011
result = a ^ b  # binary: 110, decimal: 6
print("The result of XOR operation between", a, "and", b, "is:", result)
